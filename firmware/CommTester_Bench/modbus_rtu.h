#ifndef MODBUS_RTU_H
#define MODBUS_RTU_H

#include <Arduino.h>
#include "ModbusADU.h"


// ============================================================
// CommTester — Modbus RTU Transport Layer
// ============================================================
//
// Этот класс является внутренним транспортным слоем проекта.
//
// Он отвечает за:
//   - приём RTU-кадров;
//   - передачу RTU-кадров;
//   - определение границ кадра;
//   - контроль межбайтового интервала;
//   - контроль интервала между кадрами;
//   - проверку CRC;
//   - управление линией передачи.
//
// Логика Modbus Slave / Master находится ВЫШЕ этого уровня.
//
// Внешняя библиотека ModbusRTUComm для работы проекта
// использоваться не будет.
//
// ============================================================


// ============================================================
// ERROR CODES
// ============================================================

enum ModbusRTUError : uint8_t {

  // Кадр успешно принят.
  MODBUS_RTU_SUCCESS = 0,

  // Не получен полный кадр в установленное время.
  MODBUS_RTU_TIMEOUT = 1,

  // Ошибка структуры кадра.
  MODBUS_RTU_FRAME_ERROR = 2,

  // Ошибка CRC.
  MODBUS_RTU_CRC_ERROR = 3
};


// ============================================================
// MODBUS RTU TRANSPORT
// ============================================================

class ModbusRTU {

  public:

    // --------------------------------------------------------
    // CONSTRUCTOR
    // --------------------------------------------------------
    //
    // serial:
    //   последовательный интерфейс, через который работает
    //   Modbus RTU.
    //
    // dePin / rePin:
    //   управляющие выводы RS-485.
    //
    // Для текущего CommTester через RS-232 они не нужны,
    // поэтому по умолчанию используются -1.
    //
    // В будущем это позволит использовать тот же транспорт
    // с RS-485 без изменения архитектуры.
    //

    ModbusRTU(Stream& serial,
              int dePin = -1,
              int rePin = -1);


    // --------------------------------------------------------
    // BEGIN
    // --------------------------------------------------------
    //
    // Инициализация последовательного интерфейса.
    //
    // baud:
    //   скорость передачи.
    //
    // config:
    //   формат UART.
    //
    // Для текущего проекта:
    //
    //   9600 8N1
    //

    void begin(unsigned long baud,
               uint32_t config = SERIAL_8N1);


    // --------------------------------------------------------
    // SET RESPONSE TIMEOUT
    // --------------------------------------------------------
    //
    // Устанавливает максимальное время ожидания ответа.
    //
    // Этот параметр особенно понадобится в режиме MASTER.
    //
    // ВАЖНО:
    //
    // RESPONSE TIMEOUT и t3.5 — разные параметры.
    //
    // RESPONSE TIMEOUT определяет, сколько Master ждёт
    // ответа устройства.
    //
    // t3.5 определяет границу RTU-кадра.
    //

    void setTimeout(unsigned long timeout);


    // --------------------------------------------------------
    // READ ADU
    // --------------------------------------------------------
    //
    // Ожидает и принимает один Modbus RTU кадр.
    //
    // При успешном приёме:
    //
    //   возвращается MODBUS_RTU_SUCCESS
    //
    // При ошибке:
    //
    //   MODBUS_RTU_TIMEOUT
    //   MODBUS_RTU_FRAME_ERROR
    //   MODBUS_RTU_CRC_ERROR
    //
    // Полученный кадр помещается в объект ModbusADU.
    //

    ModbusRTUError readAdu(ModbusADU& adu);


    // --------------------------------------------------------
    // WRITE ADU
    // --------------------------------------------------------
    //
    // Передаёт один Modbus RTU кадр.
    //
    // Перед отправкой выполняется подготовка линии,
    // затем передаются все байты кадра.
    //
    // После окончания передачи линия возвращается
    // в состояние приёма.
    //

    bool writeAdu(ModbusADU& adu);


  private:

    // ========================================================
    // SERIAL INTERFACE
    // ========================================================

    // Ссылка на последовательный интерфейс.
    //
    // Например:
    //
    //   Serial
    //   Serial1
    //   SoftwareSerial
    //
    Stream& _serial;


    // ========================================================
    // RS-485 CONTROL
    // ========================================================

    // DE — Driver Enable.
    //
    // Если используется RS-485:
    //
    //   HIGH → передача
    //   LOW  → приём
    //
    // Для RS-232 текущего CommTester:
    //
    //   -1
    //

    int _dePin;


    // RE — Receiver Enable.
    //
    // Может использоваться для управления приёмником
    // RS-485.
    //
    // Для текущего RS-232:
    //
    //   -1
    //

    int _rePin;


    // ========================================================
    // MODBUS RTU TIMING
    // ========================================================

    // Максимально допустимый интервал между байтами
    // одного RTU кадра.
    //
    // Единица измерения:
    //
    //   микросекунды.
    //
    // Значение будет рассчитываться из:
    //
    //   MODBUS_BAUD
    //   MODBUS_BITS_PER_CHAR
    //
    // из modbus_config.h.
    //

    unsigned long _t15;


    // Интервал тишины, соответствующий 3.5 символам.
    //
    // Используется для определения границы Modbus RTU
    // кадров.
    //
    // Единица измерения:
    //
    //   микросекунды.
    //

    unsigned long _t35;


    // ========================================================
    // BYTE TIMING
    // ========================================================

    // Время передачи одного UART-символа.
    //
    // Используется для расчёта RTU timing.
    //
    // Для 9600 8N1 примерно:
    //
    //   1042 мкс.
    //

    unsigned long _bytePeriod;


    // ========================================================
    // TRANSMISSION DELAY
    // ========================================================

    // Дополнительная задержка после окончания передачи.
    //
    // Нужна для гарантированного завершения последнего
    // символа перед переключением RS-485 из TX в RX.
    //
    // Для RS-232 обычно не требуется.
    //

    unsigned long _postDelay;


    // ========================================================
    // RESPONSE TIMEOUT
    // ========================================================

    // Максимальное время ожидания начала входящего кадра.
    //
    // Единица измерения:
    //
    //   миллисекунды.
    //
    // Устанавливается через setTimeout().
    //

    unsigned long _readTimeout;


    // ========================================================
    // INTERNAL METHODS
    // ========================================================

    // Управление направлением RS-485.
    //
    // Если DE/RE не используются, функция ничего не делает.
    //

    void setTransmitMode();
    void setReceiveMode();


    // Расчёт временных параметров после begin().
    //

    void calculateTiming();
};


#endif