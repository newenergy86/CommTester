#ifndef MODBUS_CONFIG_H
#define MODBUS_CONFIG_H


// ============================================================
// CommTester — Modbus RTU configuration
// ============================================================
//
// Этот файл содержит настройки Modbus RTU, используемые
// проектом CommTester.
//
// ВАЖНО:
//   1. Это файл НАШЕГО проекта.
//   2. Внешние библиотеки Modbus НЕ изменяются.
//   3. При переносе прошивки на другое устройство достаточно
//      перенести файлы проекта вместе с этим конфигурационным
//      файлом.
//
// Основная задача файла — собрать параметры физического
// последовательного обмена и временные параметры Modbus RTU
// в одном месте.
//
// ------------------------------------------------------------
// Основные временные параметры Modbus RTU:
//
// t1.5 — максимально допустимый интервал между байтами
//        одного RTU-кадра.
//
// t3.5 — интервал тишины на линии, используемый для определения
//        границы Modbus RTU-кадра.
//
// Эти параметры зависят от скорости передачи.
//
// На данном этапе CommTester работает с:
//
//        9600 бод
//        8N1
//
// Поэтому значения можно рассчитывать от скорости передачи,
// а не задавать вручную.
//
// ============================================================


// ============================================================
// SERIAL PARAMETERS
// ============================================================

// Скорость последовательного интерфейса.
//
// В текущей версии проекта основной Modbus/RS-232 канал
// работает со скоростью 9600 бод.
//
// Если в будущем скорость будет изменена, связанные с ней
// временные параметры Modbus должны также измениться.
//
// Пока скорость является фиксированной частью текущей
// конфигурации CommTester.

const unsigned long MODBUS_BAUD = 9600;


// Количество бит, передаваемых для одного символа.
//
// Для формата 8N1:
//
//   1 start bit
//   8 data bits
//   0 parity bits
//   1 stop bit
//
// Итого:
//
//   1 + 8 + 0 + 1 = 10 бит на один UART-символ.
//
// Этот параметр используется при расчёте времени одного
// символа и Modbus RTU таймингов.

const byte MODBUS_BITS_PER_CHAR = 10;


// ============================================================
// MODBUS RTU TIMING
// ============================================================
//
// Время здесь задаётся в микросекундах.
//
// Почему именно микросекунды?
//
// Потому что при 9600 бод длительность одного символа
// составляет примерно 1042 мкс. Миллисекунд недостаточно
// для точного управления RTU таймингами.
//
// ============================================================


// ------------------------------------------------------------
// t1.5 — межбайтовый интервал
// ------------------------------------------------------------
//
// t1.5 соответствует времени передачи 1.5 символа.
//
// Если пауза между двумя байтами кадра превышает этот
// интервал, приёмник должен рассматривать ситуацию как
// нарушение непрерывности RTU-кадра.
//
// Для 9600 бод и 8N1:
//
//   Tchar = 10 / 9600 ≈ 1.042 ms
//
//   t1.5 ≈ 1.563 ms
//
// Значение ниже рассчитано именно для текущего режима
// 9600 8N1.
//
// НЕ изменять это значение без понимания влияния на
// определение границ кадра.
//
// ------------------------------------------------------------

const unsigned long MODBUS_T15_US = 1563;


// ------------------------------------------------------------
// t3.5 — интервал между RTU-кадрами
// ------------------------------------------------------------
//
// t3.5 соответствует времени передачи 3.5 символа.
//
// Интервал тишины не менее t3.5 используется для определения
// окончания одного Modbus RTU кадра и начала следующего.
//
// Для 9600 бод и 8N1:
//
//   t3.5 ≈ 3.646 ms
//
// Значение ниже рассчитано для текущей скорости.
//
// ------------------------------------------------------------

const unsigned long MODBUS_T35_US = 3646;


// ============================================================
// RESPONSE TIMEOUT
// ============================================================
//
// MODBUS_RESPONSE_TIMEOUT_MS определяет, сколько времени
// Master ожидает начало ответа Slave.
//
// Это НЕ t3.5.
//
// Разница:
//
//   t3.5
//       относится к структуре RTU-кадра и тишине линии.
//
//   RESPONSE_TIMEOUT
//       относится к ожиданию ответа от удалённого устройства.
//
// Этот параметр особенно понадобится после реализации
// режима MASTER.
//
// ------------------------------------------------------------

const unsigned long MODBUS_RESPONSE_TIMEOUT_MS = 100;


// ============================================================
// FUTURE PARAMETERS
// ============================================================
//
// Здесь в дальнейшем можно разместить:
//
//   - задержку перед началом ответа Slave;
//   - максимальную длину RTU-кадра;
//   - таймаут ожидания первого байта;
//   - параметры RS-485 DE/RE;
//   - дополнительные диагностические таймауты.
//
// Пока эти параметры НЕ добавляем, чтобы не создавать
// настройки, которые ещё не используются кодом.
//
// ============================================================


#endif